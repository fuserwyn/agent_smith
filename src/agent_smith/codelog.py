"""Keep the Python code the agent sends to the sandbox worker, one module per step.

An :class:`EventSink` listener: every run gets a folder
``agent_code/runs/<benchmark>/<date>_<time>_<task>/`` with ``task.md`` (model, task prompt) and
``step_01.py``, ``step_02.py``, … — the thought as a header comment, the exact code the worker ran, and the
observation as a trailing comment. Handy to study a run, re-run a step by hand or diff two runs.

Off by default: ``AGENT_SMITH_CODE_DIR=<dir>`` turns it on (``AGENT_SMITH_CODE_DIR=1`` writes to ``agent_code/``
next to the project). An exam run therefore writes nothing into the student's directory; the same code is in
``solution.json`` (``sandbox_input``) and in the trace anyway. The folder ignores itself (``.gitignore`` with ``*``).
"""

from __future__ import annotations

import os
import re
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Optional

from agent_smith.config import PROJECT_ROOT

FOLDER = "agent_code"
_SAFE = re.compile(r"[^A-Za-z0-9._-]+")
_THOUGHT = re.compile(r"^\s*(?:Thought:)?\s*(.*?)(?:```|<code>|\{\s*\"|$)", re.S)


def code_root(default: Optional[Path] = None) -> Optional[Path]:
    """Where runs are written: ``$AGENT_SMITH_CODE_DIR`` (``1``/``on``: ``<default or repo>/agent_code``); None if off."""
    env = (os.environ.get("AGENT_SMITH_CODE_DIR") or "").strip()
    if env.lower() in ("", "0", "off", "false", "no"):
        return None
    if env.lower() in ("1", "on", "true", "yes"):
        return Path(default or PROJECT_ROOT) / FOLDER
    return Path(env).expanduser()


def _comment(text: str, limit: int = 4000) -> str:
    text = (text or "").rstrip()
    if len(text) > limit:
        text = text[:limit] + f"\n[... {len(text) - limit} more characters]"
    return "\n".join(("# " + line).rstrip() for line in text.splitlines()) or "#"


class CodeLog:
    """Listener ``(kind, record)`` for :class:`agent_smith.events.EventSink`. Never raises into the agent."""

    def __init__(self, root: Optional[Path], label: Optional[str] = None):
        self.root = Path(root) if root else None
        self.label = label
        self.dir: Optional[Path] = None
        self.thoughts: Dict[int, str] = {}
        self.codes: Dict[int, str] = {}
        self.header = ""

    def __call__(self, kind: str, record: Dict[str, Any]) -> None:
        if self.root is None:
            return
        if kind == "run_start":
            self._start(record)
        elif self.dir is None:
            return
        elif kind == "llm_response":
            m = _THOUGHT.match(record.get("text") or "")
            self.thoughts[int(record.get("step") or 0)] = (m.group(1) if m else "").strip()
        elif kind == "sandbox_start":
            step = int(record.get("step") or 0)
            self.codes[step] = record.get("code") or ""
            self._write(step, None)
        elif kind == "sandbox_end":
            step = int(record.get("step") or 0)
            if step in self.codes:
                self._write(step, record)

    def _start(self, r: Dict[str, Any]) -> None:
        bench = _SAFE.sub("-", str(r.get("benchmark") or "run")).strip("-") or "run"
        task = re.sub(r"-{2,}", "-", _SAFE.sub("-", str(self.label or r.get("task_id") or "task"))).strip("-")[:60] or "task"
        base = self.root / "runs" / bench  # type: ignore[operator]  (agent_code/apps/ holds projects)
        name = f"{datetime.now():%Y-%m-%d_%H-%M-%S}_{task}"
        folder, n = base / name, 2
        while folder.exists():
            folder, n = base / f"{name}-{n}", n + 1
        folder.mkdir(parents=True)
        ignore = self.root / ".gitignore"  # type: ignore[operator]
        if not ignore.exists():
            ignore.write_text("# generated by Agent Smith: the code sent to the sandbox worker, never committed\n*\n")
        self.dir = folder
        self.header = f"# Agent Smith · {bench} · task {r.get('task_id')} · model {r.get('model')}"
        (folder / "task.md").write_text(
            f"# {bench} · task {r.get('task_id')}\n\n- model: `{r.get('model')}`\n- started: {datetime.now():%Y-%m-%d %H:%M:%S}\n"
            f"- tools: {', '.join(r.get('tools') or []) or '—'}\n\n## Task prompt\n\n{r.get('task_prompt') or ''}\n",
            encoding="utf-8")

    def _write(self, step: int, end: Optional[Dict[str, Any]]) -> None:
        parts = [f"{self.header} · step {step}",
                 "# The exact code the agent sent to the sandbox worker; tools are proxied to the MCP server.", "#"]
        if self.thoughts.get(step):
            parts += ["# Thought:", _comment(self.thoughts[step], 2000)]
        parts += ["", self.codes[step].rstrip(), ""]
        if end is not None:
            status = end.get("status")
            parts += [f"# ---- observation ({status}, {end.get('duration_s', '?')} s) ----", _comment(end.get("output") or "")]
        (self.dir / f"step_{step:02d}.py").write_text("\n".join(parts) + "\n", encoding="utf-8")  # type: ignore[operator]
